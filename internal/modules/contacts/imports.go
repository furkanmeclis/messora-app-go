// TypeImport is the worker task that runs an import.
const TypeImport = "contacts:import"

// Import limits.
const (
	MaxImportBytes = 50 << 20
	importBatch    = 500
	maxColumns     = 200
	maxCellLen     = 2000
)

// ImportStore keeps uploaded files and error reports on disk.
type ImportStore struct{ root string }

func (s *ImportStore) path(key string) (string, error) {
	if key == "" || strings.Contains(key, "..") || filepath.IsAbs(key) {
		return "", errors.New("imports: invalid key")
	}
	return filepath.Join(s.root, filepath.FromSlash(key)), nil
}

func (s *ImportStore) create(key string) (*os.File, error) {
	p, err := s.path(key)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		return nil, err
	}
	return os.OpenFile(p, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o640) //nolint:gosec // key generated by Messora
}

// Open opens a stored file.
func (s *ImportStore) Open(key string) (*os.File, error) {
	p, err := s.path(key)
	if err != nil {
		return nil, err
	}
	return os.Open(p) //nolint:gosec // key generated by Messora and validated
}

func (s *ImportStore) remove(key string) {
	if p, err := s.path(key); err == nil {
		_ = os.Remove(p)
	}
}

func newKey(kind string) string {
	b := make([]byte, 16)
	_, _ = rand.Read(b)
	return "imports/" + kind + "/" + hex.EncodeToString(b) + ".csv"
}

// newCSVReader detects the delimiter (comma, semicolon or tab, as exported
// by spreadsheet programs in different locales) and skips a UTF-8 BOM.
func newCSVReader(r io.Reader) (*csv.Reader, error) {
	br := bufio.NewReaderSize(r, 64<<10)
	if b, _ := br.Peek(3); bytes.Equal(b, []byte{0xEF, 0xBB, 0xBF}) {
		_, _ = br.Discard(3)
	}
	head, _ := br.Peek(8 << 10)
	line := head
	if i := bytes.IndexByte(head, '\n'); i >= 0 {
		line = head[:i]
	}
	delim := ','
	best := bytes.Count(line, []byte{','})
	for _, d := range []rune{';', '\t'} {
		if n := bytes.Count(line, []byte(string(d))); n > best {
			delim, best = d, n
		}
	}
	cr := csv.NewReader(br)
	cr.Comma = delim
	cr.FieldsPerRecord = -1 // tolerate ragged rows; validated per row
	cr.ReuseRecord = true
	cr.LazyQuotes = true
	return cr, nil
}

// Upload stores a CSV file and returns the import with detected headers
// and a preview. The body is streamed to disk, never held in memory.
func (s *Service) Upload(ctx context.Context, filename string, body io.Reader, actor *uuid.UUID) (db.ContactImport, error) {
	filename = filepath.Base(strings.TrimSpace(filename))
	lower := strings.ToLower(filename)
	isXLSX := strings.HasSuffix(lower, ".xlsx")
	if !isXLSX && !strings.HasSuffix(lower, ".csv") && !strings.HasSuffix(lower, ".txt") {
		return db.ContactImport{}, apperr.Validation("filename", "Upload a CSV (.csv) or Excel (.xlsx) file.")
	}
	key := newKey("uploads")
	f, err := s.imp.create(key)
	if err != nil {
		return db.ContactImport{}, err
	}
	size, err := io.Copy(f, io.LimitReader(body, MaxImportBytes+1))
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err == nil && size > MaxImportBytes {
		err = apperr.Validation("file", "The file is larger than 50 MB; split it into smaller files.")
	}
	var mbe interface{ MaxBytes() int64 }
	if errors.As(err, &mbe) || (err != nil && strings.Contains(err.Error(), "request body too large")) {
		err = apperr.Validation("file", "The file is larger than 50 MB; split it into smaller files.")
	}
	if err == nil && size == 0 {
		err = apperr.Validation("file", "The file is empty.")
	}
	if err == nil && isXLSX {
		// Imports always run on CSV; workbooks are converted once here.
		err = s.imp.convertXLSX(key)
	}
	if err != nil {
		s.imp.remove(key)
		return db.ContactImport{}, err
	}

	headers, preview, rows, err := s.scan(key)
	if err != nil {
		s.imp.remove(key)
		return db.ContactImport{}, err
	}
	hj, _ := json.Marshal(headers)
	pj, _ := json.Marshal(preview)
	var imp db.ContactImport
	err = s.tx(ctx, func(q *db.Queries) error {
		imp, err = q.InsertContactImport(ctx, db.InsertContactImportParams{Filename: filename, StorageKey: key, SizeBytes: size,
			Headers: hj, Preview: pj, TotalRows: rows, CreatedBy: actor})
		if err != nil {
			return err
		}
		return audit.Record(ctx, q, audit.Entry{Action: "contact.import_upload", EntityType: "contact_import", EntityID: &imp.ID,
			Changes: map[string]any{"filename": filename, "rows": rows}})
	})
	if err != nil {
		s.imp.remove(key)
	}
	return imp, err
}

// scan reads the header, the first rows and the row count.
func (s *Service) scan(key string) (headers []string, preview [][]string, rows int64, err error) {
	f, err := s.imp.Open(key)
	if err != nil {
		return nil, nil, 0, err
	}
	defer f.Close()
	cr, _ := newCSVReader(f)
	rec, err := cr.Read()
	if err != nil {
		return nil, nil, 0, apperr.Validation("file", "Could not read a header row from the file.")
	}
	if len(rec) > maxColumns {
		return nil, nil, 0, apperr.Validation("file", fmt.Sprintf("The file has more than %d columns.", maxColumns))
	}
	seen := map[string]bool{}
	for _, h := range rec {
		h = strings.TrimSpace(h)
		if !utf8.ValidString(h) {
			return nil, nil, 0, apperr.Validation("file", "The file is not UTF-8 encoded; save it as \"CSV UTF-8\".")
		}
		if h == "" || seen[strings.ToLower(h)] {
			return nil, nil, 0, apperr.Validation("file", "Every column needs a unique, non-empty header.")
		}
		seen[strings.ToLower(h)] = true
		headers = append(headers, h)
	}
	for {
		rec, err := cr.Read()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, nil, 0, apperr.Validation("file", fmt.Sprintf("The file is not valid CSV near row %d.", rows+2))
		}
		if isBlank(rec) {
			continue
		}
		rows++
		if len(preview) < 5 {
			preview = append(preview, append([]string(nil), rec...))
		}
	}
	if rows == 0 {
		return nil, nil, 0, apperr.Validation("file", "The file has a header but no rows.")
	}
	return headers, preview, rows, nil
}

func isBlank(rec []string) bool {
	for _, v := range rec {
		if strings.TrimSpace(v) != "" {
			return false
		}
	}
	return true
}

// ImportOptions configure a run.
type ImportOptions struct {
	Mapping         map[string]string // contact field → header
	DuplicatePolicy string            // skip | update
	AddTags         []string
	GroupID         *uuid.UUID
}

var mappable = map[string]bool{"phone": true, "name": true, "email": true, "var1": true, "var2": true, "var3": true,
	"var4": true, "var5": true, "tags": true}

// Start validates the mapping and queues the import.
func (s *Service) Start(ctx context.Context, id uuid.UUID, o ImportOptions) (db.ContactImport, error) {
	imp, err := s.q.GetContactImport(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return imp, apperr.NotFound("Import not found.")
	}
	if err != nil {
		return imp, err
	}
	if imp.Status != "uploaded" {
		return imp, apperr.Conflict("IMPORT_STARTED", "This import was already started.")
	}
	var headers []string
	_ = json.Unmarshal(imp.Headers, &headers)
	known := map[string]bool{}
	for _, h := range headers {
		known[h] = true
	}
	if o.Mapping["phone"] == "" {
		return imp, apperr.Validation("mapping.phone", "Choose the column that holds phone numbers.")
	}
	for field, col := range o.Mapping {
		isAttr := strings.HasPrefix(field, "attr:") && len(field) > 5 && len(field) <= 65
		if !mappable[field] && !isAttr {
			return imp, apperr.Validation("mapping", fmt.Sprintf("Unknown contact field %q.", field))
		}
		if !known[col] {
			return imp, apperr.Validation("mapping", fmt.Sprintf("Column %q is not in the file.", col))
		}
	}
	if o.DuplicatePolicy == "" {
		o.DuplicatePolicy = "skip"
	}
	for _, t := range o.AddTags {
		if strings.TrimSpace(t) == "" || len([]rune(t)) > 60 {
			return imp, apperr.Validation("add_tags", "Tags are 1–60 characters.")
		}
	}
	mj, _ := json.Marshal(o.Mapping)
	err = s.txx(ctx, func(tx pgx.Tx, q *db.Queries) error {
		if o.GroupID != nil {
			if _, err := q.GetContactGroup(ctx, *o.GroupID); errors.Is(err, pgx.ErrNoRows) {
				return apperr.Validation("group_id", "Unknown group.")
			} else if err != nil {
				return err
			}
		}
		imp, err = q.QueueContactImport(ctx, db.QueueContactImportParams{ID: id, Mapping: mj, DuplicatePolicy: o.DuplicatePolicy,
			AddTags: nonNilSlice(o.AddTags), GroupID: o.GroupID})
		if errors.Is(err, pgx.ErrNoRows) {
			return apperr.Conflict("IMPORT_STARTED", "This import was already started.")
		}
		if err != nil {
			return err
		}
		_, err = outbox.Write(ctx, tx, outbox.TaskTopic(TypeImport), map[string]string{"import_id": id.String()}, 0)
		return err
	})
	return imp, err
}

// Cancel stops a queued or running import.
func (s *Service) Cancel(ctx context.Context, id uuid.UUID) (db.ContactImport, error) {
	imp, err := s.q.RequestImportCancel(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		cur, gerr := s.q.GetContactImport(ctx, id)
		if errors.Is(gerr, pgx.ErrNoRows) {
			return cur, apperr.NotFound("Import not found.")
		}
		return cur, apperr.Conflict("IMPORT_FINISHED", "This import has already finished.")
	}
	return imp, err
}

type rowError struct {
	line   int64
	reason string
	rec    []string
}

type counters struct{ processed, created, updated, skipped, failed int64 }

// Run executes an import. It is resumable: rows are processed in batches
// with absolute progress counters, and a restarted run skips rows already
// counted. Memory use is bounded by the batch size.
func (s *Service) Run(ctx context.Context, id uuid.UUID) error {
	imp, err := s.q.StartContactImport(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil // cancelled, finished or unknown
	}
	if err != nil {
		return err
	}
	var mapping map[string]string
	_ = json.Unmarshal(imp.Mapping, &mapping)
	var headers []string
	_ = json.Unmarshal(imp.Headers, &headers)

	f, err := s.imp.Open(imp.StorageKey)
	if err != nil {
		return s.finish(ctx, id, "failed", nil, "The uploaded file is missing.")
	}
	defer f.Close()
	cr, _ := newCSVReader(f)
	if _, err := cr.Read(); err != nil { // header
		return s.finish(ctx, id, "failed", nil, "Could not read the file header.")
	}
	col := map[string]int{}
	for i, h := range headers {
		col[h] = i
	}
	idx := map[string]int{}
	for field, h := range mapping {
		idx[field] = col[h]
	}

	c := counters{processed: imp.ProcessedRows, created: imp.CreatedCount, updated: imp.UpdatedCount,
		skipped: imp.SkippedCount, failed: imp.FailedCount}
	resumeFrom := imp.ProcessedRows
	var errs []rowError
	var batch []importRow
	var line, dataRow int64 = 1, 0

	flush := func() (bool, error) {
		if err := s.applyBatch(ctx, imp, batch, &c, &errs); err != nil {
			return false, err
		}
		batch = batch[:0]
		cancel, err := s.q.ProgressContactImport(ctx, db.ProgressContactImportParams{ID: id, ProcessedRows: c.processed,
			CreatedCount: c.created, UpdatedCount: c.updated, SkippedCount: c.skipped, FailedCount: c.failed})
		return cancel, err
	}

	for {
		rec, err := cr.Read()
		if errors.Is(err, io.EOF) {
			break
		}
		line++
		if err != nil {
			return s.finish(ctx, id, "failed", errs, fmt.Sprintf("The file is not valid CSV near line %d.", line))
		}
		if isBlank(rec) {
			continue
		}
		dataRow++
		if dataRow <= resumeFrom {
			continue // processed by an earlier, interrupted run
		}
		row, perr := parseRow(rec, idx)
		if perr != "" {
			c.processed++
			c.failed++
			if len(errs) < 100_000 {
				errs = append(errs, rowError{line: line, reason: perr, rec: append([]string(nil), rec...)})
			}
		} else {
			row.line = line
			row.rec = append([]string(nil), rec...)
			batch = append(batch, row)
		}
		if len(batch) >= importBatch {
			cancel, err := flush()
			if err != nil {
				return err
			}
			if cancel {
				return s.finish(ctx, id, "cancelled", errs, "")
			}
		}
		if ctx.Err() != nil {
			// Shutting down: progress is saved, the task will resume.
			if _, err := flush(); err != nil {
				return err
			}
			return ctx.Err()
		}
	}
	cancel, err := flush()
	if err != nil {
		return err
	}
	if cancel {
		return s.finish(ctx, id, "cancelled", errs, "")
	}
	return s.finish(ctx, id, "completed", errs, "")
}

type importRow struct {
	phone string
	name  string
	email string
	vars  [5]string
	tags  []string
	attrs map[string]string
	line  int64
	rec   []string
}

func cell(rec []string, i int, ok bool) string {
	if !ok || i >= len(rec) {
		return ""
	}
	return strings.TrimSpace(rec[i])
}

func parseRow(rec []string, idx map[string]int) (importRow, string) {
	get := func(f string) string { i, ok := idx[f]; return cell(rec, i, ok) }
	var r importRow
	for _, v := range rec {
		if len(v) > maxCellLen {
			return r, "a cell is longer than 2000 characters"
		}
		if !utf8.ValidString(v) {
			return r, "the row is not valid UTF-8"
		}
	}
	raw := get("phone")
	if raw == "" {
		return r, "phone number is missing"
	}
	phone, ok := NormalizePhone(raw)
	if !ok {
		return r, "phone number is not in international format"
	}
	r.phone = phone
	r.name = get("name")
	if len([]rune(r.name)) > 200 {
		return r, "name is longer than 200 characters"
	}
	r.email = get("email")
	if r.email != "" {
		if err := validateFields(&Fields{Email: &r.email}); err != nil {
			return r, "e-mail address is not valid"
		}
	}
	for i := range r.vars {
		r.vars[i] = get(fmt.Sprintf("var%d", i+1))
		if len([]rune(r.vars[i])) > 500 {
			return r, fmt.Sprintf("var%d is longer than 500 characters", i+1)
		}
	}
	if t := get("tags"); t != "" {
		for _, p := range strings.FieldsFunc(t, func(r rune) bool { return r == ';' || r == ',' || r == '|' }) {
			if p = strings.TrimSpace(p); p != "" {
				if len([]rune(p)) > 60 {
					return r, "a tag is longer than 60 characters"
				}
				r.tags = append(r.tags, p)
			}
		}
	}
	for f := range idx {
		if name, ok := strings.CutPrefix(f, "attr:"); ok {
			if v := get(f); v != "" {
				if r.attrs == nil {
					r.attrs = map[string]string{}
				}
				r.attrs[name] = v
			}
		}
	}
	return r, ""
}

const upsertSQL = `
INSERT INTO contacts (phone_e164, name, email, var1, var2, var3, var4, var5, attributes, source)
VALUES ($1, $2, nullif($3, '')::citext, nullif($4, ''), nullif($5, ''), nullif($6, ''), nullif($7, ''), nullif($8, ''), $9, 'import')
ON CONFLICT (tenant_id, phone_e164) DO UPDATE SET
    name       = coalesce(nullif(excluded.name, ''), contacts.name),
    email      = coalesce(excluded.email, contacts.email),
    var1       = coalesce(excluded.var1, contacts.var1),
    var2       = coalesce(excluded.var2, contacts.var2),
    var3       = coalesce(excluded.var3, contacts.var3),
    var4       = coalesce(excluded.var4, contacts.var4),
    var5       = coalesce(excluded.var5, contacts.var5),
    attributes = contacts.attributes || excluded.attributes,
    updated_at = now()
WHERE $10::boolean
RETURNING id, (xmax = 0) AS inserted`

// applyBatch upserts one batch in a single transaction.
func (s *Service) applyBatch(ctx context.Context, imp db.ContactImport, rows []importRow, c *counters, errs *[]rowError) error {
	if len(rows) == 0 {
		return nil
	}
	update := imp.DuplicatePolicy == "update"
	return s.txx(ctx, func(tx pgx.Tx, q *db.Queries) error {
		b := &pgx.Batch{}
		for _, r := range rows {
			attrs, _ := json.Marshal(nonNil(r.attrs))
			b.Queue(upsertSQL, r.phone, r.name, r.email, r.vars[0], r.vars[1], r.vars[2], r.vars[3], r.vars[4], attrs, update)
		}
		res := tx.SendBatch(ctx, b)
		ids := make([]uuid.UUID, len(rows))
		for i := range rows {
			var inserted bool
			err := res.QueryRow().Scan(&ids[i], &inserted)
			switch {
			case errors.Is(err, pgx.ErrNoRows):
				c.skipped++
			case err != nil:
				_ = res.Close()
				return err
			case inserted:
				c.created++
			default:
				c.updated++
			}
			c.processed++
		}
		if err := res.Close(); err != nil {
			return err
		}
		tagIDs := map[string]uuid.UUID{}
		tagFor := func(name string) (uuid.UUID, error) {
			k := strings.ToLower(name)
			if id, ok := tagIDs[k]; ok {
				return id, nil
			}
			t, err := q.UpsertTag(ctx, db.UpsertTagParams{Name: name, Color: "gray"})
			tagIDs[k] = t.ID
			return t.ID, err
		}
		var members []uuid.UUID
		for i, r := range rows {
			if ids[i] == uuid.Nil {
				continue // skipped duplicate: left untouched
			}
			for _, t := range append(append([]string(nil), imp.AddTags...), r.tags...) {
				tid, err := tagFor(t)
				if err != nil {
					return err
				}
				if err := q.AddContactTag(ctx, db.AddContactTagParams{ContactID: ids[i], TagID: tid}); err != nil {
					return err
				}
			}
			members = append(members, ids[i])
		}
		if imp.GroupID != nil && len(members) > 0 {
			if _, err := q.AddGroupMembers(ctx, db.AddGroupMembersParams{GroupID: *imp.GroupID, ContactIds: members}); err != nil {
				return err
			}
		}
		return nil
	})
}

func (s *Service) finish(ctx context.Context, id uuid.UUID, status string, errs []rowError, msg string) error {
	var key *string
	if len(errs) > 0 {
		k := newKey("errors")
		if err := s.writeErrors(k, errs); err != nil {
			return err
		}
		key = &k
	}
	var last *string
	if msg != "" {
		last = &msg
	}
	bg := context.WithoutCancel(ctx)
	return s.q.FinishContactImport(bg, db.FinishContactImportParams{ID: id, Status: status, ErrorReportKey: key, LastError: last})
}

func (s *Service) writeErrors(key string, errs []rowError) error {
	f, err := s.imp.create(key)
	if err != nil {
		return err
	}
	w := csv.NewWriter(f)
	_ = w.Write([]string{"line", "reason", "row"})
	for _, e := range errs {
		_ = w.Write(safeCSV([]string{fmt.Sprint(e.line), e.reason, strings.Join(e.rec, " | ")}))
	}
	w.Flush()
	if err := w.Error(); err != nil {
		_ = f.Close()
		return err
	}
	return f.Close()
}

func nonNilSlice(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}
