// The campaign report (Phase 16C 4.4): an XLSX workbook with the sheets
// Özet, Maliyet, Teslimat, Alıcılar, Segment, Etiket and Tahmin vs Gerçek,
// and a one-page PDF summary. Both are generated by the export job.

// ReportSheets are the names of the report workbook's sheets.
var ReportSheets = []string{"Özet", "Maliyet", "Teslimat", "Alıcılar", "Segment", "Etiket", "Tahmin vs Gerçek"}

type reportData struct {
	c   db.Campaign
	a   Analysis
	fva ForecastVsActual
}

func (s *Service) reportData(ctx context.Context, id uuid.UUID) (reportData, error) {
	c, err := s.q.GetCampaign(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return reportData{}, apperr.NotFound("Campaign not found.")
	}
	if err != nil {
		return reportData{}, err
	}
	a, err := s.Analysis(ctx, id)
	if err != nil {
		return reportData{}, err
	}
	fva, err := s.CompareForecast(ctx, id)
	if err != nil {
		return reportData{}, err
	}
	return reportData{c: c, a: a, fva: fva}, nil
}

func fmtTime(t *time.Time) string {
	if t == nil {
		return ""
	}
	return t.UTC().Format("2006-01-02 15:04 UTC")
}

func fmtRate(v *float64) string {
	if v == nil {
		return ""
	}
	return strconv.FormatFloat(*v*100, 'f', 2, 64) + "%"
}

func fmtNum(v *float64) string {
	if v == nil {
		return ""
	}
	return strconv.FormatFloat(*v, 'f', -1, 64)
}

func sourceLabel(src string) string {
	if src == SourceMeta {
		return "Meta"
	}
	return "Sistem hesaplaması"
}

// summaryRows is the Özet sheet (also the PDF's table).
func (d reportData) summaryRows() [][]string {
	rows := [][]string{
		{"Kampanya", d.c.Name, ""},
		{"Durum", d.c.Status, ""},
		{"Şablon", d.c.TemplateName + " (" + d.c.TemplateLanguage + ")", ""},
		{"Başlangıç", fmtTime(d.c.StartedAt), ""},
		{"Bitiş", fmtTime(d.c.FinishedAt), ""},
		{"", "", ""},
		{"Metrik", "Değer", "Kaynak"},
	}
	for _, m := range d.a.Metrics {
		rows = append(rows, []string{m.Key, strconv.FormatInt(m.Value, 10), sourceLabel(m.Source)})
	}
	r := d.a.Rates
	for _, x := range []struct {
		k string
		v *float64
	}{{"sent_rate", r.Sent}, {"delivery_rate", r.Delivery}, {"read_rate", r.Read}, {"reply_rate", r.Reply},
		{"positive_rate", r.Positive}, {"negative_rate", r.Negative}, {"opt_out_rate", r.OptOut}} {
		rows = append(rows, []string{x.k, fmtRate(x.v), sourceLabel(SourceSystem)})
	}
	rows = append(rows, []string{"cost_estimate", d.a.CostEstimate + " " + d.a.Currency, "Sistem hesaplaması (Meta fiyat kategorisi × fiyat kartı)"})
	return rows
}

// WriteReportXLSX writes the multi-sheet report; it returns the number of
// recipient rows.
func (s *Service) WriteReportXLSX(ctx context.Context, id uuid.UUID, w io.Writer) (int64, error) {
	d, err := s.reportData(ctx, id)
	if err != nil {
		return 0, err
	}
	tmp := os.TempDir()
	if s.exports != nil {
		tmp = s.exports.tmpDir()
	}
	book := excelize.NewFile(excelize.Options{TmpDir: tmp})
	defer func() { _ = book.Close() }()
	_ = book.SetSheetName("Sheet1", ReportSheets[0])
	for _, name := range ReportSheets[1:] {
		if _, err := book.NewSheet(name); err != nil {
			return 0, err
		}
	}
	sheet := func(name string, rows [][]string) error {
		sw, err := book.NewStreamWriter(name)
		if err != nil {
			return err
		}
		x := &sheetWriter{sw: sw}
		for _, r := range rows {
			if err := x.Write(r); err != nil {
				return err
			}
		}
		return x.Close()
	}
	if err := sheet("Özet", d.summaryRows()); err != nil {
		return 0, err
	}
	cost := [][]string{{"Kategori", "Tür", "Mesaj", "Fiyatsız (fiyat kartında yok)", "Tutar", "Para birimi", "Kaynak"}}
	for _, c := range d.a.CostBreakdown {
		cost = append(cost, []string{c.Category, c.Type, strconv.FormatInt(c.Messages, 10), strconv.FormatInt(c.Unpriced, 10), c.Cost, c.Currency,
			"Sistem hesaplaması (mesaj başı)"})
	}
	for _, x := range d.a.AICost {
		cost = append(cost, []string{"ai", "", strconv.FormatInt(x.Requests, 10), "", x.Cost, x.Currency, "Sistem hesaplaması (AI kullanımı)"})
	}
	if d.a.TotalCost != "" {
		cost = append(cost, []string{"toplam (Meta + AI)", "", "", "", d.a.TotalCost, d.a.Currency, "Sistem hesaplaması"})
	}
	cost = append(cost, []string{}, []string{"Gün", "Kategori", "Hacim", "Meta maliyeti", "Para birimi", "", "Meta (numaranın tüm mesajları, uzlaştırma)"})
	for _, x := range d.a.Reconciled {
		cost = append(cost, []string{x.Day.Format(time.DateOnly), x.Category, strconv.FormatInt(x.Volume, 10), x.Cost, x.Currency, "", ""})
	}
	if err := sheet("Maliyet", cost); err != nil {
		return 0, err
	}
	del := [][]string{{"Saat (UTC)", "Gönderildi", "Teslim", "Okundu", "Cevap", "Başarısız"}}
	for _, h := range d.a.Hourly {
		del = append(del, []string{h.Hour.UTC().Format("2006-01-02 15:00"), strconv.FormatInt(h.Sent, 10), strconv.FormatInt(h.Delivered, 10),
			strconv.FormatInt(h.Read, 10), strconv.FormatInt(h.Replied, 10), strconv.FormatInt(h.Failed, 10)})
	}
	del = append(del, []string{}, []string{"Ulaşılamama sebebi", "Kişi"})
	for k, v := range d.a.Classes {
		del = append(del, []string{k, strconv.FormatInt(v, 10)})
	}
	if err := sheet("Teslimat", del); err != nil {
		return 0, err
	}
	sw, err := book.NewStreamWriter("Alıcılar")
	if err != nil {
		return 0, err
	}
	rx := &sheetWriter{sw: sw}
	n, err := s.writeRecipients(ctx, id, RecipientFilter{}, rx)
	if err != nil {
		return n, err
	}
	if err := rx.Close(); err != nil {
		return n, err
	}
	for _, x := range []struct{ sheet, dim string }{{"Segment", DimSegment}, {"Etiket", DimTag}} {
		bs, err := s.Breakdown(ctx, id, x.dim, "")
		if err != nil {
			return n, err
		}
		rows := [][]string{{"Ad", "Alıcı", "Gönderildi", "Teslim", "Okundu", "Cevap", "Olumlu", "Olumsuz", "Çıkış", "Maliyet"}}
		for _, b := range bs {
			rows = append(rows, []string{b.Label, strconv.FormatInt(b.Recipients, 10), strconv.FormatInt(b.Sent, 10), strconv.FormatInt(b.Delivered, 10),
				strconv.FormatInt(b.Read, 10), strconv.FormatInt(b.Replied, 10), strconv.FormatInt(b.Positive, 10), strconv.FormatInt(b.Negative, 10),
				strconv.FormatInt(b.OptedOut, 10), b.Cost})
		}
		if err := sheet(x.sheet, rows); err != nil {
			return n, err
		}
	}
	fva := [][]string{{"Metrik", "Tahmin", "Gerçek", "Fark", "Fark %"}}
	if d.fva.Forecast == nil {
		fva = append(fva, []string{"Bu kampanya için saklanmış tahmin yok.", "", "", "", ""})
	} else {
		for _, m := range d.fva.Metrics {
			fva = append(fva, []string{m.Metric, fmtNum(m.Forecast), fmtNum(m.Actual), fmtNum(m.Delta), fmtNum(m.DeltaPct)})
		}
		if d.fva.Forecast.Rates.Status != RatesOK {
			fva = append(fva, []string{}, []string{"Teslim ve etkileşim tahmini için yeterli geçmiş yoktu.", "", "", "", ""})
		}
	}
	if err := sheet("Tahmin vs Gerçek", fva); err != nil {
		return n, err
	}
	_, err = book.WriteTo(w)
	return n, err
}

// WriteReportPDF writes the one-page summary (Go fonts, BSD licensed,
// cover Turkish characters).
func (s *Service) WriteReportPDF(ctx context.Context, id uuid.UUID, w io.Writer) error {
	d, err := s.reportData(ctx, id)
	if err != nil {
		return err
	}
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.AddUTF8FontFromBytes("go", "", goregular.TTF)
	pdf.AddUTF8FontFromBytes("go", "B", gobold.TTF)
	pdf.SetTitle("Kampanya raporu: "+d.c.Name, true)
	pdf.SetCreator("Messora", true)
	pdf.AddPage()
	pdf.SetFont("go", "B", 16)
	pdf.CellFormat(0, 10, "Kampanya raporu", "", 1, "L", false, 0, "")
	pdf.SetFont("go", "", 10)
	pdf.CellFormat(0, 6, fmt.Sprintf("Oluşturuldu: %s", time.Now().UTC().Format("2006-01-02 15:04 UTC")), "", 1, "L", false, 0, "")
	pdf.Ln(2)
	for i, r := range d.summaryRows() {
		style := ""
		if i == 6 {
			style = "B"
		}
		pdf.SetFont("go", style, 9)
		pdf.CellFormat(55, 5.5, r[0], "", 0, "L", false, 0, "")
		pdf.CellFormat(70, 5.5, r[1], "", 0, "L", false, 0, "")
		pdf.CellFormat(0, 5.5, r[2], "", 1, "L", false, 0, "")
	}
	if f := d.fva.Forecast; f != nil {
		pdf.Ln(3)
		pdf.SetFont("go", "B", 11)
		pdf.CellFormat(0, 7, "Tahmin vs gerçek", "", 1, "L", false, 0, "")
		pdf.SetFont("go", "", 9)
		for _, m := range d.fva.Metrics {
			pdf.CellFormat(55, 5, m.Metric, "", 0, "L", false, 0, "")
			pdf.CellFormat(35, 5, fmtNum(m.Forecast), "", 0, "R", false, 0, "")
			pdf.CellFormat(35, 5, fmtNum(m.Actual), "", 0, "R", false, 0, "")
			pdf.CellFormat(0, 5, fmtNum(m.DeltaPct), "", 1, "R", false, 0, "")
		}
		if f.Rates.Status != RatesOK {
			pdf.CellFormat(0, 5, "Teslim ve etkileşim tahmini için yeterli geçmiş yoktu.", "", 1, "L", false, 0, "")
		}
	}
	pdf.Ln(3)
	pdf.SetFont("go", "", 8)
	pdf.MultiCell(0, 4, "Meta: Meta'nın bildirdiği durumlar (gönderildi, teslim, okundu, başarısız) ve fiyat kategorisi. "+
		"Sistem hesaplaması: Messora'nın hesapladığı cevap, olumlu/olumsuz dönüş, çıkış, tahmin ve fiyat kartına göre maliyet. "+
		"Meta kullanıcı başına spam bildirimi vermez; spam ve kalite göstergeleri toplu sinyallerdir.", "", "L", false)
	return pdf.Output(w)
}
