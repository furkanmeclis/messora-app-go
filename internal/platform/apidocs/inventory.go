package apidocs

import (
	"bytes"
	"fmt"
	"strings"
)

// Inventory renders the public endpoint inventory (docs/API.md) from the
// public document, grouped like the reference's navigation.
func Inventory(pub Doc) []byte {
	var b bytes.Buffer
	b.WriteString("# Public API inventory\n\n")
	b.WriteString("<!-- Generated by `make api-docs` from api/openapi.yaml. Do not edit. -->\n\n")
	b.WriteString("Every operation an API key (`Authorization: Bearer msk_…`) can call. Every workspace\n")
	b.WriteString("has its own API address, `https://<workspace>.messora.tech/api/v1` or its custom\n")
	b.WriteString("domain, and a key works only at its own workspace's address (there is no shared API\n")
	b.WriteString("host). The interactive reference with request/response examples and code samples is\n")
	b.WriteString("served at each workspace's address under `/docs/api`, with that workspace's base URL\n")
	b.WriteString("in every example; the machine-readable document at `/api/v1/openapi.json`.\n")
	b.WriteString("Paths are relative to `/api/v1`. **Scope**: any one of the listed scopes is enough.\n")
	b.WriteString("**Rate limit**: the default plan's budget; a workspace's plan may set another\n")
	b.WriteString("(docs/ENTITLEMENTS.md).\n\n")

	ops := Operations(pub)
	fmt.Fprintf(&b, "%d operations.\n", len(ops))
	byTag := map[string][]Operation{}
	for _, o := range ops {
		tags := asStrings(o.Op["tags"])
		tag := "other"
		if len(tags) > 0 {
			tag = tags[0]
		}
		byTag[tag] = append(byTag[tag], o)
	}
	display := map[string]string{}
	for _, t := range asList(pub["tags"]) {
		if n, ok := asMap(t)["x-displayName"].(string); ok {
			display[fmt.Sprint(asMap(t)["name"])] = n
		}
	}
	for _, g := range asList(pub["x-tagGroups"]) {
		gm := asMap(g)
		fmt.Fprintf(&b, "\n## %s\n", gm["name"])
		for _, t := range asStrings(gm["tags"]) {
			list := byTag[t]
			if len(list) == 0 {
				continue
			}
			title := t
			if n, ok := display[t]; ok {
				title = n
			}
			fmt.Fprintf(&b, "\n### %s\n\n", title)
			b.WriteString("| Method | Path | Summary | Scope | Rate limit |\n|---|---|---|---|---|\n")
			for _, o := range list {
				scopes := Scopes(o.Op)
				scope := "any key"
				if len(scopes) > 0 {
					scope = "`" + strings.Join(scopes, "`, `") + "`"
				}
				limit := ""
				if rl := asMap(o.Op[RateLimitExtension]); rl != nil {
					limit = fmt.Sprintf("%v/min per key", rl["limit"])
				}
				fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s |\n", strings.ToUpper(o.Method), o.Path,
					cell(o.Op["summary"]), scope, limit)
			}
		}
	}
	return b.Bytes()
}

func cell(v any) string {
	s, _ := v.(string)
	return strings.ReplaceAll(strings.TrimSpace(s), "|", `\|`)
}
