package phonecountry

import "testing"

func TestOf(t *testing.T) {
	cases := map[string]string{
		"+905551112233":  "TR",
		"905551112233":   "TR",
		"+14155550100":   "US",
		"+14165550100":   "CA", // Toronto
		"+18095550100":   "DO",
		"+17875550100":   "PR",
		"+447700900123":  "GB",
		"+4915112345678": "DE",
		"+79161234567":   "RU",
		"+77011234567":   "KZ",
		"+971501234567":  "AE",
		"+966501234567":  "SA",
		"+5511987654321": "BR",
		"+5215512345678": "MX",
		"+919876543210":  "IN",
		"+2348012345678": "NG",
		"+35312345678":   "IE",
		"+38050123456":   "UA",
		"+85291234567":   "HK",
		"+8613812345678": "CN",
		"+59991234567":   "CW",
		"":               "",
		"+1":             "",
		"+12":            "",
		"+0123456789":    "",
		"+90 555":        "",
		"+999123456":     "",
	}
	for in, want := range cases {
		if got := Of(in); got != want {
			t.Errorf("Of(%q) = %q, want %q", in, got, want)
		}
	}
}
